def _filename(doc_id: str, title: str) -> str:
    safe = re.sub(r'[\\/:*?"<>|]+', "-", title)
    return f"{doc_id}-{safe}.md"


def render_markdown(entry: dict) -> str:
    lines = [
        f"# {entry['title']}",
        "",
        f"> 文档编号：{entry['id']}",
        f"> 版本：{entry['version']}",
        f"> 生效日期：{EFFECTIVE_DATE}",
        f"> 责任人：{entry['owner']}",
        f"> 权限级别：{entry['permission']}",
        "",
        "## 1. 文档说明",
        "",
        entry["summary"],
        "",
    ]
    for index, (heading, content) in enumerate(entry["sections"], start=2):
        lines.append(f"## {index}. {heading}")
        lines.append("")
        for item in content:
            lines.append(item)
            lines.append("")
    lines.extend(
        [
            "## 附则",
            "",
            f"1. 本制度由{entry['owner']}负责解释和修订，自发布之日起施行。",
            "2. 本制度为模拟文档，仅用于知识库问答系统的学习演示，不代表任何真实企业的管理规定。",
            "3. 如遇法律法规或公司经营情况变化，由相关责任部门提出修订，经审批后发布新版本。",
            "",
        ]
    )
    return "\n".join(lines).rstrip() + "\n"


def write_docs(docs: list[dict], target: Path, meta_name: str) -> None:
    target.mkdir(parents=True, exist_ok=True)
    meta = []
    for entry in docs:
        filename = _filename(entry["id"], entry["title"])
        (target / filename).write_text(render_markdown(entry), encoding="utf-8")
        meta.append(
            {
                "doc_id": entry["id"],
                "filename": filename,
                "title": entry["title"],
                "category": entry["category"],
                "source": entry["source"],
                "method": entry["method"],
                "update_date": EFFECTIVE_DATE,
                "permission": entry["permission"],
                "owner": entry["owner"],
                "status": "已清洗",
                "remark": entry["remark"],
            }
        )
    (META_DIR / meta_name).write_text(
        json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8"
    )


